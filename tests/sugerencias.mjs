import { createRequire } from 'node:module';
const require = createRequire('/home/claude/.npm-global/lib/node_modules/');
const { chromium } = require('playwright');
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 412, height: 900 }, deviceScaleFactor: 2 });
await ctx.addInitScript(() => localStorage.setItem('texsting.settings', JSON.stringify({ token: 'abc123', theme: 'dark' })));
const page = await ctx.newPage(); const errs = []; page.on('pageerror', (e) => errs.push(e.message));
let enviado = null;
await page.route('https://docs.google.com/**', (r) => { enviado = r.request().postData(); r.fulfill({ status: 200, body: 'ok' }); });
await page.goto('http://127.0.0.1:8080/index.html');
await page.click('[aria-label="Ajustes"]').catch(async () => page.click('.icon-btn[title="Ajustes"]'));
await page.waitForSelector('text=Enviar una sugerencia');
await page.screenshot({ path: '/home/claude/tests/shots/sug-0.png', fullPage: true });
await page.click('button:has-text("Enviar una sugerencia")');
await page.waitForSelector('.sug-texto');
console.log('botón al inicio deshabilitado:', await page.isDisabled('button:has-text("Enviar sugerencia")'));
await page.fill('.sug-texto', 'palabra '.repeat(205));
console.log('contador:', await page.textContent('.sug-contador'), '| aviso:', await page.textContent('.sug-aviso'), '| deshabilitado:', await page.isDisabled('button:has-text("Enviar sugerencia")'));
await page.fill('.sug-texto', 'Me gustaría un modo de presentación para beamer con ñ y tildes: áéíóú.');
console.log('contador:', await page.textContent('.sug-contador'));
await page.screenshot({ path: '/home/claude/tests/shots/sug-1.png' });
