await page.click('button:has-text("Volver a Ajustes")');
await page.click('button:has-text("Enviar una sugerencia")');
await page.fill('.sug-texto', 'otra idea');
console.log('bloqueado:', await page.isDisabled('button:has-text("Enviar sugerencia")'), '|', await page.textContent('.sug-aviso'));
await page.screenshot({ path: '/home/claude/tests/shots/sug-3.png' });
console.log('errores:', errs);
